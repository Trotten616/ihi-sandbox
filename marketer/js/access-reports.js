  function search(query, groupFilter, priorityOnly) {
    const q = (query || "").trim().toLowerCase();
    return reports.filter((rep) => {
      if (groupFilter && groupFilter !== "all" && rep.group !== groupFilter) return false;
      if (priorityOnly && rep.priority !== "primary") return false;
      if (!q) return true;
      const hay = [rep.plainName, rep.accessName, rep.tip, rep.group].join(" ").toLowerCase();
      return hay.indexOf(q) !== -1;
    });
  }

